#define MESSAGE_ENTITLEMENT 0x186B58B1u

// Every opaque object Echo reads (user, room, arrays, launch details, ...) is this one empty
// block: its accessors below answer with no data, the user's ID and name, or "".
static uint64_t g_empty[32];
static uint64_t g_error[4];
static char g_nonce[33];
static int g_initialized;

typedef struct Message {
    struct Message* next;
    uint32_t type;
    ovrRequest id;
    bool error;
    const char* text;
} Message;

static pthread_mutex_t g_lock = PTHREAD_MUTEX_INITIALIZER;
static Message* g_head;
static Message* g_tail;
static ovrRequest g_next_id = 1;

static ovrRequest Reply(uint32_t type, bool error, const char* text) {
    Message* m = calloc(1, sizeof(Message));
    pthread_mutex_lock(&g_lock);
    ovrRequest id = g_next_id++;
    if (m) {
        m->type = type;
        m->id = id;
        m->error = error;
        m->text = text;
        if (g_tail) g_tail->next = m; else g_head = m;
        g_tail = m;
    }
    pthread_mutex_unlock(&g_lock);
    return id;
}


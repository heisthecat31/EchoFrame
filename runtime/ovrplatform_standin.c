// EchoQuestXR Platform SDK stand-in -- libovrplatformloader.so for the Steam Frame build.
//
// Meta's libovrplatformloader.so starts the Platform SDK by binding to Horizon OS's
// com.oculus.platformsdkruntime; when that isn't installed (Lepton on Steam Frame) it tries
// to open com.oculus.systemactivities' error screen, fails, and throws OVRPlatformException,
// which aborts Echo the moment it creates its OVR provider (libpnsovr.so):
//   OVRPlatform-Loader: platformSDK_Initialize: Failed to load PlatformSDK driver (-1)!
//   OVRPlatform-Loader: DisplayErrorAndExit: Failed to launch SystemActivities
//
// This stand-in exports the same C functions and answers locally. What Echo's OVR provider
// (libpnsovr.so, build 4987566) does with the answers:
//   ovr_PlatformInitializeAndroid      0 (success); anything else stops Echo
//   entitlement check                  a reply that isn't an error; an error reply makes
//                                      Echo exit (HardExit(1) in the provider's Update)
//   logged-in user, org-scoped ID,     replies with this stand-in's user; Echo logs in to the
//   access token, user proof           community servers with its own config.json, and the
//                                      community build hard-codes the app-scoped user ID
//   friends, purchases, invites,       empty lists
//   rich presence
//   rooms, invite/friend/checkout      an error reply ("not available"): Echo logs it and
//   panels                             carries on (its error handlers only retry when the
//                                      error text is JSON saying is_transient)
//   microphone                         real: AAudio capture (see ovr_Microphone_Create)
//   VoIP, P2P packets                  handles that produce no data
// Replies arrive through ovr_PopMessage on the next poll, as they would from Meta's.
// Every other export of Meta's loader (ovrplatform_exports.txt) is a stub generated by
// runtime/build.py that logs once and returns 0.
//
// Logs to logcat under EchoQuestXR ("Platform SDK: ...").
